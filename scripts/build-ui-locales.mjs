import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const translations = JSON.parse(await readFile(path.join(root, "shared/ui-nb.json"), "utf8"));
const entries = Object.entries(translations).sort(([a], [b]) => a.localeCompare(b, "en"));
const id = (key) => "ui_" + createHash("sha256").update(key).digest("hex").slice(0, 12);
const xml = (value) => JSON.stringify(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
async function write(relative, contents) {
  const file = path.join(root, relative);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, contents);
}
for (const language of ["en", "nb"]) {
  const values = entries.map(([key, translated]) => [key, language === "en" ? key : translated]);
  const android = values.map(([key, value]) => `    <string name="${id(key)}" formatted="false">${xml(value)}</string>`).join("\n");
  await write(`apps/android/app/src/main/res/${language === "en" ? "values" : "values-nb"}/ui_strings.xml`,
    `<!-- Generated by scripts/build-ui-locales.mjs. -->\n<resources>\n${android}\n</resources>\n`);
  await write(`apps/ios/Sources/${language}.lproj/Localizable.strings`,
    "// Generated by scripts/build-ui-locales.mjs.\n" +
    values.map(([key, value]) => `${JSON.stringify(key)} = ${JSON.stringify(value)};`).join("\n") + "\n");
  const privacy = {
    NSCameraUsageDescription: "Take a picture of your hosting setup QR code.",
    NSLocalNetworkUsageDescription: "Publish your website to hosting on your local network.",
  };
  await write(`apps/ios/Sources/${language}.lproj/InfoPlist.strings`,
    "// Generated by scripts/build-ui-locales.mjs.\n" +
    Object.entries(privacy).map(([key, value]) =>
      `${JSON.stringify(key)} = ${JSON.stringify(language === "en" ? value : translations[value])};`
    ).join("\n") + "\n");
}
await write("apps/android/app/src/main/java/no/webeasy/app/UiCatalog.kt",
  "// Generated by scripts/build-ui-locales.mjs.\npackage no.webeasy.app\n\ninternal object UiCatalog {\n    val resources = mapOf(\n" +
  entries.map(([key]) => `        ${JSON.stringify(key)} to R.string.${id(key)},`).join("\n") + "\n    )\n}\n");
console.log(`Generated English and Norwegian Bokmål resources for ${entries.length} interface messages.`);
